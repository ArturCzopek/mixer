say("## Per player: S vs how they actually played in the mixes");
say();
say(
  "Players with at least 5 used maps. *Mixer Rating* is Mixer Rating 2 from popflash stats with " +
    "popflash's real KAST. The last line is the Spearman correlation across players.",
);
say();
say("| Player | Maps | Mean S (default) | Mean E | Mixer Rating | Win % |");
say("|---|---|---|---|---|---|");
const per = new Map<
  string,
  { s: number[]; e: number[]; r: number[]; w: number[] }
>();
for (const m of maps) {
  for (const [team, won] of [
    [m.team1, m.pred.y === 1],
    [m.team2, m.pred.y === 0],
  ] as const)
    for (const p of team) {
      const x = per.get(p.steamId) ?? { s: [], e: [], r: [], w: [] };
      x.s.push(p.S);
      x.e.push(p.E);
      x.r.push(m.ratings.get(p.steamId)!);
      x.w.push(won ? 1 : 0);
      per.set(p.steamId, x);
    }
}
const rows = [...per]
  .filter(([, x]) => x.s.length >= 5)
  .sort((a, b) => mean(b[1].r) - mean(a[1].r));
for (const [id, x] of rows)
  say(
    `| ${data.nameOf.get(id) ?? id} | ${x.s.length} | ${f(mean(x.s), 0)} | ${f(mean(x.e), 0)} | ${f(mean(x.r), 2)} | ${pct(mean(x.w))} |`,
  );
say();
say(
  `Spearman(mean S, Mixer Rating) = ${f(
    spearman(
      rows.map(([, x]) => mean(x.s)),
      rows.map(([, x]) => mean(x.r)),
    ),
    2,
  )}; ` +
    `Spearman(mean E, Mixer Rating) = ${f(
      spearman(
        rows.map(([, x]) => mean(x.e)),
        rows.map(([, x]) => mean(x.r)),
      ),
      2,
    )}.`,
);
